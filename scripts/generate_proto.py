"""Generate Python gRPC and protobuf stubs from .proto definitions."""

from pathlib import Path
import sys

from grpc_tools import protoc


def main():
    """Compile proto/node.proto into the rpc.generated package."""
    repo_root = Path(__file__).resolve().parent.parent
    proto_dir = repo_root / "proto"
    proto_file = proto_dir / "node.proto"
    out_dir = repo_root / "src" / "sync_music_player" / "rpc" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)

    init_file = out_dir / "__init__.py"
    if not init_file.exists():
        init_file.write_text('"""Generated protobuf and gRPC modules."""\n', encoding="utf-8")

    args = [
        "grpc_tools.protoc",
        f"-I{proto_dir}",
        f"--python_out={out_dir}",
        f"--pyi_out={out_dir}",
        f"--grpc_python_out={out_dir}",
        str(proto_file),
    ]
    exit_code = protoc.main(args)
    if exit_code != 0:
        sys.exit(exit_code)

    # Rewrite top-level import generated by protoc so package-relative imports work cleanly.
    grpc_file = out_dir / "node_pb2_grpc.py"
    content = grpc_file.read_text(encoding="utf-8")
    patched = content.replace(
        "import node_pb2 as node__pb2",
        "from . import node_pb2 as node__pb2",
    )
    grpc_file.write_text(patched, encoding="utf-8")
    print(f"Generated gRPC stubs in {out_dir}")


if __name__ == "__main__":
    main()
